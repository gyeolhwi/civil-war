/**
 * 결과 페이지 모달용 섹션 추림: "꼭 지켜주세요" + 3·4·5번 섹션만.
 * 형식이 달라(헤딩 못 찾음) 추릴 게 없으면 전체를 반환(graceful fallback).
 * 제목(# ...)은 제외 — 모달 헤더가 따로 있으므로.
 */
export function rulesSubset(md: string): string {
  const lines = md.split("\n");
  const sections: { heading: string; raw: string }[] = [];
  let cur: { heading: string; raw: string } | null = null;
  for (const line of lines) {
    if (line.startsWith("## ")) {
      cur = { heading: line.slice(3).trim(), raw: `${line}\n` };
      sections.push(cur);
    } else if (cur) {
      cur.raw += `${line}\n`;
    }
  }
  const want = sections.filter(
    (s) =>
      /꼭 지켜주세요|기본 매너/.test(s.heading) || /^[345]\./.test(s.heading),
  );
  if (!want.length) return md;
  return want.map((s) => s.raw.trimEnd()).join("\n\n");
}
